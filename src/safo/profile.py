"""The `profile` block of agents.yaml: how to brief an agent, every behavioural claim tied to a pointer to evidence.

This module is the loader half of docs/superpowers/specs/2026-10-11-agent-profiles.md (sections 1 and 7.3). It parses
and validates; it renders nothing and it resolves nothing. An evidence pointer is checked for its FORM and for which
claim it may support. Whether the lesson or the outcomes it names exists is decided by the resolution stage, which
reads the evidence files.

The rule it enforces is "no trait without a measurement": an `unmeasured` profile claims nothing about the model, and
a `profiled` one has at least one `do`, `dont` or `must_not_get` entry, each with a pointer. Text that will be rendered
into files an agent obeys is kept to one printable line without Markdown structure, private paths, e-mail addresses
or a short list of policy-overriding phrases (section 7.3). That list is a tripwire for the lazy attack and for
accidents. It is not a semantic filter and it has false negatives by construction.
"""

