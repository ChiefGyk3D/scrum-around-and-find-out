class Budget:
    """Counts list entries across the whole file, so one file cannot carry an unbounded amount of rendered text."""

    def __init__(self, r: Reader) -> None:
        self.r = r
        self.entries = 0
        self.checked: set[tuple[str, str, str]] = set()  # (directory, template path, content digest) already validated

    def take(self, count: int) -> None:
        self.entries += count
        if self.entries > MAX_ENTRIES:
            raise self.r.fail("profiles", f"at most {MAX_ENTRIES} entries in the file")


_INLINE_LINK = re.compile(r"\[([^\[\]]*)\]\([^()]*\)")  # bracket-free text: linear on hostile input


def slugify(heading: str) -> str:
    """The GitHub-style anchor of a heading: lower case, punctuation dropped, spaces to hyphens."""
    text = _INLINE_LINK.sub(r"\1", heading.strip())  # [text](target) keeps its text, as GitHub renders it
    return re.sub(r"[^\w\- ]", "", text.lower()).replace(" ", "-")


def _outcomes_form(r: Reader, ref: str, path: str) -> None:
    bits = ref.split(":", 3)
    if len(bits) != 4 or bits[0] != "v1":
        raise r.fail(path, "expected outcomes:v1:<range>:<subject>:<metric><op><number>")
    _, span, subject, expression = bits
    try:
        parse_span(span)
    except ValueError as err:
        raise r.fail(path, str(err)) from None
    names = subject.split("/")
    if len(names) > 2 or not all(IDENTIFIER.fullmatch(n) for n in names):
        raise r.fail(path, "the outcomes subject is <agent> or <agent>/<model>")
    if METRIC.fullmatch(expression) is None:
        raise r.fail(
            path, "expected <metric><op><number>, with a metric from the outcomes list and an op of >= > <= < ="
        )


def _config_form(r: Reader, ref: str, path: str, claim: str) -> None:
    if not ref.startswith("/") or re.search(r"~(?![01])", ref):
        raise r.fail(path, "expected an RFC 6901 JSON Pointer starting with /")
    seg = [s.replace("~1", "/").replace("~0", "~") for s in ref.split("/")[1:]]
    fields = CONFIG_FIELDS.get(claim, {})
    if (
        len(seg) >= 5
        and seg[0] == "agents"
        and seg[1]
        and seg[2] == "endpoints"
        and ENDPOINT_INDEX.fullmatch(seg[3])
        and fields.get(seg[4]) == len(seg)
        and all(seg)
    ):
        return
    raise r.fail(path, f"a config pointer for {claim} must address one of: {', '.join(fields)} of an endpoint")


def parse_evidence(r: Reader, value: object, path: str, claim: str = "claim", label: str = "claim") -> Evidence:
    """Check the form of a pointer and that its kind may support this kind of claim; touch no file."""
    if not isinstance(value, str) or not value.strip():
        raise r.fail(path, "expected an evidence pointer (a string)")
    if len(value) > MAX_POINTER or POINTER_CHARS.fullmatch(value) is None:
        raise r.fail(path, f"expected an evidence pointer of printable characters, at most {MAX_POINTER}")
    kind, _, ref = value.partition(":")
    if kind not in ("lessons", "outcomes", "config") or not ref:
        raise r.fail(
            path, "expected lessons:<slug>, outcomes:v1:<range>:<subject>:<metric><op><number> or config:<pointer>"
        )
    if kind not in KINDS_FOR[claim]:
        raise r.fail(path, f"a {kind} pointer cannot support a {label} claim (allowed: {', '.join(KINDS_FOR[claim])})")
    if kind == "lessons" and LESSON_SLUG.fullmatch(ref) is None:
        raise r.fail(path, "expected lessons:<slug> with a slug of lower-case letters, digits, hyphens and underscores")
    if kind == "outcomes":
        _outcomes_form(r, ref, path)
    if kind == "config":
        _config_form(r, ref, path, claim)
    return Evidence(value, kind, ref)


# -- text rules (7.3, 2.5) ----------------------------------------------------------------------------------------

_PRIVATE_PATHS = (
    re.compile(r"(?:^|[\s(\"'=,;:\[])~/"),
    re.compile(r"/home/", re.IGNORECASE),
    re.compile(r"/Users/", re.IGNORECASE),
    re.compile(r"(?<![A-Za-z0-9])[A-Za-z]:[\\/]"),
    re.compile(r"\\Users\\", re.IGNORECASE),
    re.compile(r"file://", re.IGNORECASE),
)
_EMAIL = re.compile(r"([A-Za-z0-9._%+-]+)@([A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+)")
_PLACEHOLDER_DOMAINS = {"example.com", "example.org"}
_PLACEHOLDER_LOCALS = {"N0CALL", "N0TST"}
_TRIPWIRES = (
    re.compile(
        r"\b(?:ignore|disregard)\s+(?:all\s+|any\s+)?(?:the\s+|your\s+)?(?:previous|prior|above)\s+(?:instructions|rules)"
    ),
    re.compile(r"\boverride\s+(?:all\s+|any\s+)?(?:the\s+|your\s+)?(?:instructions|restrictions)"),
    re.compile(r"\b(?:print|send)\s+(?:all\s+|any\s+)?(?:the\s+|your\s+)?(?:credentials|tokens)"),
)
_LEADING = ("#", ">", "-", "*", "```", "~~~", "<!--")


_BACKSLASH_ESCAPE = re.compile(r"\\([!-/:-@\[-`{-~])")


def _squash(text: str) -> str:
    """What a reader sees, for comparison: character references and backslash escapes decoded (one round), NFKC,
    invisible format characters (zero-width, bidi, soft hyphen) dropped, case-folded, whitespace collapsed."""
    decoded = _BACKSLASH_ESCAPE.sub(r"\1", html.unescape(text[:MAX_DECODE]))
    visible = "".join(c for c in unicodedata.normalize("NFKC", decoded) if unicodedata.category(c) != "Cf")
    return " ".join(visible.casefold().split())


def _variants(text: str) -> list[str]:
    """The text as written, character references decoded, NFKC of each, and up to two rounds of percent-decoding."""
    seen: list[str] = []
    frontier = [text, html.unescape(text[:MAX_DECODE])]
    for _ in range(3):
        following = []
        for candidate in frontier:
            for variant in (candidate, unicodedata.normalize("NFKC", candidate)):
                if variant not in seen:
                    seen.append(variant)
            following.append(urllib.parse.unquote(candidate))
        frontier = following
    return seen


def private_problem(text: str) -> str:
    """'' when the text carries no private path and no e-mail address; else the problem, never the text.

    The text is checked as written, with character references decoded, NFKC-normalised, and after up to two rounds of
    percent-decoding, so full-width look-alikes and %2F-style encodings are caught as well. Confusable letters from
    other scripts in an e-mail host are not (docs/limits.md).
    """
    for candidate in _variants(text):
        if any(p.search(candidate) for p in _PRIVATE_PATHS):
            return "contains a private path (a home directory, a drive path or a file URL)"
        for m in _EMAIL.finditer(candidate):
            if m[2].lower() not in _PLACEHOLDER_DOMAINS and m[1].upper() not in _PLACEHOLDER_LOCALS:
                return "contains an e-mail address"
    return ""


def tripwire_problem(text: str) -> str:
    squashed = _squash(text)
    if any(t.search(squashed) for t in _TRIPWIRES):
        return "contains a policy-overriding phrase"
    return ""


_BOUNDARY = _squash(BOUNDARY_PARAGRAPH)
_BOUNDARY_WINDOWS = frozenset(_BOUNDARY[i : i + BOUNDARY_WINDOW] for i in range(len(_BOUNDARY) - BOUNDARY_WINDOW + 1))


def spoof_problem(text: str) -> str:
    squashed = _squash(text)
    # one pass of a sliding window over the input against a set of protected windows: linear, not one search per window
    copied = any(
        squashed[i : i + BOUNDARY_WINDOW] in _BOUNDARY_WINDOWS for i in range(len(squashed) - BOUNDARY_WINDOW + 1)
    )
    if _squash(GENERATED_MARKER) in squashed or copied:
        return "contains generated-header or policy-boundary text"
    return ""


def check_text(r: Reader, value: object, path: str, limit: int) -> str:
    """One printable line that cannot become a heading, fence, comment, placeholder, path or address when rendered."""
    text = r.string(value, path)
    if len(text) > limit:
        raise r.fail(path, f"expected at most {limit} characters")
    if not text.isprintable():
        raise r.fail(path, "expected one line of printable text (no control, line-break or invisible characters)")
    if text.lstrip().startswith(_LEADING):
        raise r.fail(path, "must not start with Markdown structure (# > - * a code fence or an HTML comment)")
    if any(x in text for x in ("```", "~~~", "<!--", "{{", "}}")):
        raise r.fail(path, "contains markup that would break the generated structure (a fence, a comment or braces)")
    for problem in (private_problem(text), spoof_problem(text), tripwire_problem(text)):
        if problem:
            raise r.fail(path, problem)
    return text


# -- templates and personas: confined reads ---------------------------------------------------------------------------


def template_path_problem(rel: object) -> str:
    if not isinstance(rel, str) or not rel:
        return "expected a relative path"
    if len(rel) > MAX_PATH:
        return f"expected a path of at most {MAX_PATH} characters"
    if not rel.isprintable() or "\\" in rel:
        return "expected a path of printable characters without a backslash"
    if rel.startswith("/"):
        return "expected a relative path, not an absolute one"
    if any(part in ("", ".", "..") for part in rel.split("/")):
        return "expected a path without empty, . or .. segments"
    return ""


def read_confined(base: Path, rel: str, limit: int) -> bytes:
    """At most limit + 1 bytes of the regular file `rel` under `base`, never through a symlink.

    Each directory is opened relative to the one above with O_NOFOLLOW, the file with O_NOFOLLOW and O_NONBLOCK (a FIFO
    cannot hang the open), and the type is asked of the descriptor. Raises OSError for everything that is not a file.
    """
    parts = rel.split("/")
    fd = os.open(base, os.O_RDONLY | os.O_DIRECTORY | os.O_CLOEXEC)
    try:
        for part in parts[:-1]:
            nxt = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC, dir_fd=fd)
            os.close(fd)
            fd = nxt
        leaf = os.open(parts[-1], os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC, dir_fd=fd)
    finally:
        os.close(fd)
    try:
        if not stat.S_ISREG(os.fstat(leaf).st_mode):
            raise OSError(errno.EINVAL, "not a regular file")
        chunks: list[bytes] = []
        total = 0
        while True:
            chunk = os.read(leaf, min(65_536, limit + 1 - total))
            if not chunk:
                break
            chunks.append(chunk)
            total += len(chunk)
            if total > limit:
                break
        return b"".join(chunks)
    finally:
        os.close(leaf)


def read_text_file(r: Reader, base: Path, rel: str, path: str, what: str, *, missing_ok: bool = False) -> str | None:
    """The decoded file, or None when `missing_ok` and it (or a directory above it) does not exist."""
    try:
        raw = read_confined(base, rel, MAX_TEMPLATE)
    except FileNotFoundError:
        if missing_ok:
            return None
        raise r.fail(path, f"cannot read the {what} (it does not exist)") from None
    except OSError:
        raise r.fail(path, f"cannot read the {what} (a symbolic link, a directory or not a regular file)") from None
    if len(raw) > MAX_TEMPLATE:
        raise r.fail(path, f"{what} larger than {MAX_TEMPLATE} bytes")
    try:
        return raw.decode("utf-8")
    except UnicodeDecodeError:
        raise r.fail(path, f"{what} not valid UTF-8") from None


_FENCE_OPEN = re.compile(r"^ {0,3}(`{3,}|~{3,})(.*)$")
_PLACEHOLDER = re.compile(r"\{\{([a-z_]+)\}\}")
_ANY_BRACES = re.compile(r"\{\{([^{}]*)\}\}")
_HEADING_ONE = re.compile(r"^ {0,3}#(?:\s|$)|^ {0,3}=+\s*$")
# CommonMark HTML blocks that a blank line does not end (types 1 to 5): the opener, and what ends that block. Type 1
# ends at its OWN closing tag, so the closer is built from the tag the block opened with.
_RAW_TAG = re.compile(r"^ {0,3}<(pre|script|style|textarea)(?:\s|>|$)", re.IGNORECASE)
_HTML_BLOCKS = (
    (re.compile(r"^ {0,3}<!--"), re.compile(r"--!?>")),  # HTML5 also ends a comment at --!>
    (re.compile(r"^ {0,3}<\?"), re.compile(r"\?>")),
    (re.compile(r"^ {0,3}<!\[CDATA\["), re.compile(r"\]\]>")),
    (re.compile(r"^ {0,3}<![A-Za-z]"), re.compile(r">")),
)


_BLANK = re.compile(r"^\s*$")
_BLOCK_TAGS = (
    "address|article|aside|base|basefont|blockquote|body|caption|center|col|colgroup|dd|details|dialog|dir|div|dl|dt"
    "|fieldset|figcaption|figure|footer|form|frame|frameset|h1|h2|h3|h4|h5|h6|head|header|hr|html|iframe|legend|li"
    "|link|main|menu|menuitem|nav|noframes|ol|optgroup|option|p|param|search|section|summary|table|tbody|td|tfoot|th"
    "|thead|title|tr|track|ul"
)
_BLOCK_TAG = re.compile(r"^ {0,3}</?(?:" + _BLOCK_TAGS + r")(?:[ \t]|/?>|$)", re.IGNORECASE)


_ATTR_VALUE = r"""(?:[^\s"'=<>`]+|'[^']*'|"[^"]*")"""
_TAG_ATTR = r"(?:[ \t]+[A-Za-z_:][A-Za-z0-9_.:-]*(?:[ \t]*=[ \t]*" + _ATTR_VALUE + r")?)"
# CommonMark type 7: a complete open or closing tag and nothing else on the line (type 1 names are caught earlier)
_LONE_TAG = re.compile(
    r"^ {0,3}(?:<[A-Za-z][A-Za-z0-9-]*" + _TAG_ATTR + r"*[ \t]*/?>|</[A-Za-z][A-Za-z0-9-]*[ \t]*>)[ \t]*$"
)
_ATX = re.compile(r"^ {0,3}#{1,6}(?:[ \t]|$)")


def _html_block_end(line: str, in_paragraph: bool = False) -> tuple[int, re.Pattern[str]] | None:
    """(where the opener ends, the pattern that ends the block) when the line opens a raw HTML block."""
    raw = _RAW_TAG.match(line)
    if raw:
        # a closing tag may carry whitespace or attributes before the > (HTML5 tokenizer): </script >, </pre foo>
        return raw.end(), re.compile(r"</" + raw[1] + r"(?:[\s/][^>]*)?>", re.IGNORECASE)
    for start, end in _HTML_BLOCKS:
        m = start.match(line)
        if m:
            return m.end(), end
    block = _BLOCK_TAG.match(line)
    if block:
        return block.end(), _BLANK  # CommonMark type 6: ends at the next blank line
    if not in_paragraph and _LONE_TAG.match(line):
        return len(line), _BLANK  # type 7: cannot interrupt a paragraph; ends at the next blank line
    return None


def block_constructs(lines: list[str]) -> list[str]:
    """Which lines are inside a fenced code block or a raw HTML block (comment, pre, div ...): see `_constructs`."""
    return _constructs(lines)


def _constructs(lines: list[str]) -> list[str]:
    """For each line, '' when it is ordinary text, 'fence' or 'html' when it is inside (or closes) such a block."""
    inside: list[str] = []
    fence: tuple[str, int] | None = None
    ender: re.Pattern[str] | None = None
    paragraph = False  # the previous line is paragraph text, which a type 7 block cannot interrupt
    for line in lines:
        was_paragraph, paragraph = paragraph, False
        if fence is not None:
            inside.append("fence")
            closer = re.fullmatch(r" {0,3}(" + re.escape(fence[0]) + r"{" + str(fence[1]) + r",})[ \t]*", line)
            if closer:
                fence = None
            continue
        if ender is not None:
            inside.append("html")
            if ender.search(line):
                ender = None
            continue
        opener = _FENCE_OPEN.match(line)
        if opener and not (opener[1][0] == "`" and "`" in opener[2]):
            fence = (opener[1][0], len(opener[1]))
            inside.append("")
            continue
        opened = _html_block_end(line, was_paragraph)
        if opened and not opened[1].search(line, opened[0]):
            ender = opened[1]
        paragraph = opened is None and bool(line.strip()) and _ATX.match(line) is None
        inside.append("")
    return inside


def check_template(r: Reader, text: str, path: str) -> None:
    """The placement rules of spec 1.4: a placeholder is a whole line between blank lines, once, outside any fence."""
    if any(c not in "\n\t" and not c.isprintable() for c in text):
        raise r.fail(path, "contains a control character (only newline and tab are allowed)")
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()  # the newline that ends the file is not a line of its own
    seen: set[str] = set()
    inside = _constructs(lines)
    for i, line in enumerate(lines):
        if "{{" not in line and "}}" not in line:
            continue
        if any(n not in PLACEHOLDERS for n in _ANY_BRACES.findall(line)):
            raise r.fail(
                path, "unknown placeholder (allowed: " + ", ".join("{{" + p + "}}" for p in PLACEHOLDERS) + ")"
            )
        whole = _PLACEHOLDER.fullmatch(line)
        if whole is None:
            raise r.fail(
                path, "a placeholder must be the whole line, with nothing before or after it (malformed or inline)"
            )
        if inside[i] == "fence":
            raise r.fail(path, "a placeholder cannot sit inside a code fence")
        if inside[i] == "html":
            raise r.fail(path, "a placeholder cannot sit inside a raw HTML block (a comment, pre, script or style)")
        if whole[1] in seen:
            raise r.fail(path, "a placeholder may appear at most once; this one appears more than once")
        seen.add(whole[1])
        if i > 0 and lines[i - 1] != "":
            raise r.fail(path, "a placeholder needs a blank line before it")
        if i + 1 < len(lines) and lines[i + 1] != "":
            raise r.fail(path, "a placeholder needs a blank line after it")
    for line in lines:
        if line.strip() == "---":
            raise r.fail(path, "contains a front-matter fence or rule (---)")
        if _HEADING_ONE.match(line):
            raise r.fail(path, "contains a level-1 heading")
    for problem in (spoof_problem(text), private_problem(text), tripwire_problem(text)):
        if problem:
            raise r.fail(path, problem)


