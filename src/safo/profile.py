def _limit(r: Reader, raw: object, path: str, claim: str, bounds: tuple[int, int]) -> Limit:
    m = r.mapping(raw, path, _SETTING, _SETTING)
    value = r.integer(m["value"], f"{path}.value", minimum=bounds[0])
    if value > bounds[1]:
        raise r.fail(f"{path}.value", f"expected an integer from {bounds[0]} to {bounds[1]}")
    return Limit(value, parse_evidence(r, m["evidence"], f"{path}.evidence", claim, claim))


def _thinking(r: Reader, raw: object, path: str) -> Thinking:
    m = r.mapping(raw, path, _SETTING, _SETTING)
    value = r.choice(m["value"], f"{path}.value", THINKING)
    return Thinking(value, parse_evidence(r, m["evidence"], f"{path}.evidence", "thinking", "thinking"))


def _entries(r: Reader, raw: object, path: str, budget: Budget) -> list[Any]:
    items = r.seq(raw, path)
    if len(items) > MAX_LIST:
        raise r.fail(path, f"at most {MAX_LIST} entries")
    budget.take(len(items))
    return items


def _claims(r: Reader, raw: object, path: str, key: str, budget: Budget) -> tuple[Claim, ...]:
    out = []
    for i, item in enumerate(_entries(r, raw, path, budget)):
        m = r.mapping(item, f"{path}[{i}]", {"text", "evidence"}, {"text", "evidence"})
        out.append(
            Claim(
                check_text(r, m["text"], f"{path}[{i}].text", MAX_TEXT),
                parse_evidence(r, m["evidence"], f"{path}[{i}].evidence", "claim", key),
            )
        )
    return tuple(out)


def _shape_claims(r: Reader, raw: object, path: str, budget: Budget) -> tuple[ShapeClaim, ...]:
    out: list[ShapeClaim] = []
    for i, item in enumerate(_entries(r, raw, path, budget)):
        m = r.mapping(item, f"{path}[{i}]", {"shape", "evidence"}, {"shape", "evidence"})
        shape = r.string(m["shape"], f"{path}[{i}].shape")
        for j, earlier in enumerate(out):
            if earlier.shape == shape:
                raise r.fail(f"{path}[{i}]", f"duplicate of must_not_get[{j}]")
        out.append(
            ShapeClaim(shape, parse_evidence(r, m["evidence"], f"{path}[{i}].evidence", "claim", "must_not_get"))
        )
    return tuple(out)


def _no_duplicates(r: Reader, path: str, do: tuple[Claim, ...], dont: tuple[Claim, ...]) -> None:
    seen: dict[str, str] = {}
    for key, claims in (("do", do), ("dont", dont)):
        for i, c in enumerate(claims):
            norm = _squash(c.text)
            if norm in seen:
                raise r.fail(f"{path}.{key}[{i}]", f"duplicate of {seen[norm]}")
            seen[norm] = f"{key}[{i}]"


def _traits(
    r: Reader, m: Mapping[str, Any], path: str, status: str, budget: Budget
) -> tuple[tuple[Claim, ...], tuple[Claim, ...], tuple[ShapeClaim, ...]]:
    for key in ("do", "dont", "must_not_get"):
        if key in m and status == "unmeasured":
            raise r.fail(f"{path}.{key}", "an unmeasured agent has no traits")
    do = _claims(r, m.get("do", []), f"{path}.do", "do", budget)
    dont = _claims(r, m.get("dont", []), f"{path}.dont", "dont", budget)
    _no_duplicates(r, path, do, dont)
    must = _shape_claims(r, m.get("must_not_get", []), f"{path}.must_not_get", budget)
    if status == "profiled" and not (do or dont or must):
        raise r.fail(path, "a profiled agent needs at least one do, dont or must_not_get entry")
    return do, dont, must


def _gate(r: Reader, raw: object, path: str, budget: Budget) -> ReviewGateSpec:
    m = r.mapping(raw, path, {"required", "reviewer_differs", "checks"}, {"required", "reviewer_differs", "checks"})
    for key in ("required", "reviewer_differs"):
        if m[key] is not True:
            raise r.fail(f"{path}.{key}", "expected true")
    checks: list[ReviewCheck] = []
    for i, item in enumerate(_entries(r, m["checks"], f"{path}.checks", budget)):
        c = r.mapping(item, f"{path}.checks[{i}]", {"code", "evidence"}, {"code", "evidence"})
        code = r.choice(c["code"], f"{path}.checks[{i}].code", REVIEW_CODES)
        for j, earlier in enumerate(checks):
            if earlier.code == code:
                raise r.fail(f"{path}.checks[{i}].code", f"duplicate of checks[{j}]")
        evidence = parse_evidence(r, c["evidence"], f"{path}.checks[{i}].evidence", "claim", "review check")
        checks.append(ReviewCheck(code, evidence))
    return ReviewGateSpec(True, True, tuple(checks))


def _models(r: Reader, raw: object, path: str, budget: Budget) -> tuple[tuple[str, ModelLayer], ...]:
    layers = r.mapping(raw, path, set(raw) if isinstance(raw, Mapping) else set())
    out = []
    for model, body in layers.items():
        if not isinstance(model, str) or IDENTIFIER.fullmatch(model) is None:
            raise r.fail(path, f"{model!r} is not a model id (letters, digits, . _ - and at most 64 characters)")
        p = f"{path}.{model}"
        m = r.mapping(body, p, _LAYER_KEYS, {"status"})
        status = r.choice(m["status"], f"{p}.status", STATUSES)
        thinking = _thinking(r, m["thinking"], f"{p}.thinking") if "thinking" in m else None
        do, dont, must = _traits(r, m, p, status, budget)
        out.append((model, ModelLayer(status, thinking, do, dont, must)))
    return tuple(out)


def _persona(r: Reader, m: Mapping[str, Any], path: str, kind: str, base_dir: Path | None) -> tuple[str, str]:
    if "persona" not in m:
        return "", ""
    if kind != "claude":
        raise r.fail(f"{path}.persona", "only a claude agent has a persona")
    persona = r.string(m["persona"], f"{path}.persona")
    if PERSONA.fullmatch(persona) is None:
        raise r.fail(f"{path}.persona", "expected a persona name: lower-case letters, digits and hyphens")
    if base_dir is None:
        return persona, ""
    text = None
    for place in PERSONA_PLACES:
        text = read_text_file(r, base_dir, f"{place}/{persona}.md", f"{path}.persona", "persona file", missing_ok=True)
        if text is not None:
            break
    if text is None:
        raise r.fail(f"{path}.persona", f"no persona file {persona!r} in {' or '.join(PERSONA_PLACES)}")
    problem = private_problem(text)
    if problem:
        raise r.fail(f"{path}.persona", f"the persona file {problem}")
    return persona, text


def _brief(
    r: Reader, m: Mapping[str, Any], path: str, kind: str, persona: str, base_dir: Path | None, budget: Budget
) -> Brief | None:
    if "brief" not in m:
        if kind != "copilot" and not (kind == "claude" and persona):
            raise r.fail(f"{path}.brief", "required (a claude profile may name a persona instead)")
        return None
    b = r.mapping(m["brief"], f"{path}.brief", {"template", "inline"})
    if len(b) != 1:
        raise r.fail(f"{path}.brief", "needs exactly one of template or inline")
    if "inline" in b:
        return Brief(inline=check_text(r, b["inline"], f"{path}.brief.inline", MAX_INLINE))
    rel = b["template"]
    problem = template_path_problem(rel)
    if problem:
        raise r.fail(f"{path}.brief.template", problem)
    text = ""
    if base_dir is not None:
        text = read_text_file(r, base_dir, rel, f"{path}.brief.template", "template") or ""
        key = (str(base_dir), rel, hashlib.sha256(text.encode()).hexdigest())
        if key not in budget.checked:  # a template several profiles name is validated once per load
            check_template(r, text, f"{path}.brief.template")
            budget.checked.add(key)
    return Brief(template=rel, template_text=text)


def parse_profile(r: Reader, raw: object, path: str, *, kind: str, base_dir: Path | None, budget: Budget) -> Profile:
    """One agent's profile. With a `base_dir`, templates and personas are read (confined) and checked; without, not."""
    if kind == "human":
        raise r.fail(path, "a human takes no profile")
    m = r.mapping(raw, path, _PROFILE_KEYS, {"status"})
    status = r.choice(m["status"], f"{path}.status", STATUSES)
    persona, persona_text = _persona(r, m, path, kind, base_dir)
    brief = _brief(r, m, path, kind, persona, base_dir, budget)

    ceiling = (
        _limit(r, m["context_ceiling"], f"{path}.context_ceiling", "context_ceiling", CONTEXT_BOUNDS)
        if "context_ceiling" in m
        else None
    )
    cap = _limit(r, m["output_cap"], f"{path}.output_cap", "output_cap", OUTPUT_BOUNDS) if "output_cap" in m else None
    if ceiling and cap and cap.value > ceiling.value:
        raise r.fail(
            f"{path}.output_cap.value",
            f"{cap.value} is above the context_ceiling; expected at most the context_ceiling",
        )
    thinking = _thinking(r, m["thinking"], f"{path}.thinking") if "thinking" in m else None

    do, dont, must = _traits(r, m, path, status, budget)

    gate = None
    if "review_gate" in m:
        if kind not in GATED_KINDS:
            raise r.fail(f"{path}.review_gate", f"only {', '.join(GATED_KINDS)} has a review gate")
        gate = _gate(r, m["review_gate"], f"{path}.review_gate", budget)

    models: tuple[tuple[str, ModelLayer], ...] = ()
    if "models" in m:
        if status == "unmeasured":
            raise r.fail(f"{path}.models", "an unmeasured agent has no traits")
        if kind not in LAYERED_KINDS:
            raise r.fail(f"{path}.models", f"only {', '.join(LAYERED_KINDS)} has model layers")
        models = _models(r, m["models"], f"{path}.models", budget)

    return Profile(status, persona, persona_text, brief, ceiling, cap, thinking, do, dont, must, gate, models)


# -- cross-checks against the rest of the file ------------------------------------------------------------------


def check_profiles(r: Reader, agents: tuple[Agent, ...], shapes: tuple[Shape, ...], warnings: list[str]) -> None:
    """Checks that need the other blocks: shapes named in must_not_get, endpoints of an ollama agent, reviewers."""
    by_name = {s.name: s for s in shapes}
    for agent in agents:
        p = agent.profile
        if p is None:
            continue
        base = f"agents.{agent.id}.profile"
        layers = [(base, p.must_not_get)] + [
            (f"{base}.models.{model}", layer.must_not_get) for model, layer in p.models
        ]
        for where, claims in layers:
            for i, c in enumerate(claims):
                at = f"{where}.must_not_get[{i}].shape"
                shape = by_name.get(c.shape)
                if shape is None:
                    raise r.fail(at, f"{c.shape!r} is not a shape (shapes: {', '.join(by_name)})")
                if agent.id in shape.prefer:
                    raise r.fail(at, f"shape {c.shape!r} prefers {agent.id}, so it cannot be listed in must_not_get")
                if agent.id in shape.fallback:
                    warnings.append(f"{at}: shape {c.shape!r} falls back to {agent.id}, which lists it in must_not_get")
        if agent.kind == "ollama":
            _check_endpoints(r, agent, p)
    for agent in agents:
        if agent.profile is None or agent.profile.review_gate is None:
            continue
        for shape in shapes:
            if agent.id not in shape.chain:
                continue
            at = f"shapes.{shape.name}.reviewer"
            if not shape.reviewer:
                raise r.fail(at, f"needs a reviewer because {agent.id} has a review_gate")
            if agent.id in shape.reviewer:
                raise r.fail(at, f"{agent.id} cannot review its own work (it has a review_gate)")


def _check_endpoints(r: Reader, agent: Agent, p: Profile) -> None:
    """Profile ceilings may only be stricter than the endpoints, and thinking must agree with every endpoint."""
    base = f"agents.{agent.id}.profile"
    if p.context_ceiling is not None:
        bound = min(
            [e.num_ctx_max for e in agent.endpoints] + [n for e in agent.endpoints for _, n in e.loaded_num_ctx]
        )
        if p.context_ceiling.value > bound:
            raise r.fail(
                f"{base}.context_ceiling.value",
                f"{p.context_ceiling.value} is above {bound}, the smallest endpoint num_ctx_max or loaded_num_ctx",
            )
    if p.thinking is not None:
        if p.thinking.value == "default":
            raise r.fail(
                f"{base}.thinking.value",
                "'default' is not allowed for an ollama agent: an endpoint default is always explicit",
            )
        want = p.thinking.value == "on"
        if any(e.think != want for e in agent.endpoints):
            raise r.fail(
                f"{base}.thinking.value", f"{p.thinking.value!r} does not match every endpoint's think default"
            )
