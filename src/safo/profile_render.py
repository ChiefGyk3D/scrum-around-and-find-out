"""Rendering the verified profiles into the instruction file each harness reads (spec section 2).

Pure functions from a `VerifiedAgents` (the profiles, with the persona and template text the loader already read and
the resolved evidence) to a mapping of relative path to bytes. Nothing here touches a file. `scripts/gen_profiles.py`
writes and checks the result; `safo.harness_tree` is the filesystem half.

Every file carries one header line and the policy-boundary paragraph, and the Model profile section is fixed text with
the profile's own lines in fixed slots. Two digests are in the header (spec 2.4):

- the MANIFEST digest binds the sources: the agent's profile data, the persona and template bytes, the output path, the
  harness, `RENDER_FORMAT`, the renderer version and the resolved evidence. A stale manifest means a source changed;
- the BODY digest is the SHA-256 of the whole file with the header line removed, so a hand edit of anything, including a
  Claude file's front matter, is caught even when the header was left alone.

The digests are traceability and tamper-evidence for a reader who holds the sources. They are not a signature: they are
not secret and do not stop someone who can rewrite the sources and the files together (docs/limits.md).

The renderer refuses; it never repairs or truncates. A persona or template that tries to impersonate a generated
section, a front matter that is not plain tools, a path-shaped agent id and a file over 64 KiB are all `RenderError`s.
"""

