#!/usr/bin/env python3
# SPDX-License-Identifier: Apache-2.0
"""Generate an owner-runnable plan script from a branch-protection audit snapshot (issue #541).

The audit file is the table `safo protection --all` style audits produce: a header line starting `repo|vis|branch|`
and one `repo|vis|branch|prot|ctx|strict|conv|rev|force|del|adm|ss|pp|drift` row per repository. From it this writes
one bash script that, per repository, calls `scripts/apply-baseline.sh` with the snapshot's default branch, visibility
and protection state as expectations, so a repository that changed since the snapshot is refused:

  - no rule yet                         -> basic gate (force push and deletion off, nothing required)
  - a rule with a `CI green` check but strict or conversation resolution off -> the standard
  - a rule without a `CI green` check   -> basic gate
  - each repository named with --secret  -> secret scanning and push protection (public repositories)

Empty repositories are never touched; repositories named with --skip NAME=REASON are listed with the reason and not
touched. The script is dry run by default and writes only with the word `apply`. This generator writes a file and
runs nothing against GitHub.
"""

from __future__ import annotations

import argparse
import ast
import os
import re
import shlex
import sys
from pathlib import Path

NAME_RE = re.compile(r"^[A-Za-z0-9._-]{1,100}$")
BRANCH_RE = re.compile(r"^[A-Za-z0-9._/-]{1,200}$")
HEADER = "repo|vis|branch|"


def parse_audit(text: str) -> list[dict[str, str]]:
    lines = text.splitlines()
    start = next((i for i, ln in enumerate(lines) if ln.startswith(HEADER)), None)
    if start is None:
        raise ValueError("no header line starting 'repo|vis|branch|' in the audit file")
    keys = lines[start].split("|")
    rows = []
    for ln in lines[start + 1 :]:
        if not ln.strip():
            continue
        cells = ln.split("|")
        if len(cells) != len(keys):
            raise ValueError(f"row has {len(cells)} fields, the header has {len(keys)}: {ln[:80]!r}")
        rows.append(dict(zip(keys, cells, strict=True)))
    return rows


def has_ci_green(ctx: str) -> bool:
    try:
        names = ast.literal_eval(ctx)
    except (ValueError, SyntaxError):
        return False
    return isinstance(names, list) and any(n == "CI green" or str(n).endswith(" / CI green") for n in names)


def plan(
    rows: list[dict[str, str]], skips: dict[str, str], secrets: list[str]
) -> tuple[list[str], list[tuple[str, str]]]:
    actions: list[str] = []
    skipped: list[tuple[str, str]] = []
    by_name = {r["repo"]: r for r in rows}
    for name in secrets:
        if name not in by_name:
            raise ValueError(f"--secret {name}: not in the audit file")
    for r in rows:
        name, vis, branch = r["repo"], r["vis"].lower(), r["branch"]
        if not NAME_RE.fullmatch(name):
            raise ValueError(f"refusing repository name {name!r}")
        if vis not in ("public", "private"):
            raise ValueError(f"{name}: visibility {r['vis']!r} is not PUBLIC or PRIVATE")
        if name in skips:
            skipped.append((name, skips[name]))
            continue
        if r["prot"] == "EMPTY":
            skipped.append((name, "empty repository, no default branch"))
            continue
        if not BRANCH_RE.fullmatch(branch):
            raise ValueError(f"{name}: refusing default branch {branch!r}")
        if r["prot"] == "NONE":
            actions.append(f"{name}|{vis}|{branch}|basic|none")
        elif r["prot"] == "YES":
            drift = set(r["drift"].split(","))
            if not has_ci_green(r["ctx"]):
                actions.append(f"{name}|{vis}|{branch}|basic|rule")
            elif drift & {"strict", "conv"}:
                actions.append(f"{name}|{vis}|{branch}|standard|rule")
        else:
            raise ValueError(f"{name}: unknown protection state {r['prot']!r}")
        if name in secrets:
            if vis != "public":
                raise ValueError(f"--secret {name}: only public repositories")
            actions.append(f"{name}|{vis}|{branch}|secret-scanning|-")
    for name in secrets:
        if name in skips:
            raise ValueError(f"--secret {name}: also skipped")
    return actions, skipped


TEMPLATE = r"""#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
# Generated by scripts/gen-protection-plan.py from the audit snapshot __SNAPSHOT__ (issue #541). THE OWNER RUNS THIS.
#
#   bash PLAN            dry run: reads each repository (GET only), prints every change, writes nothing
#   bash PLAN apply      writes, one repository at a time: backup, write, read back, ROLLBACK line
#
# A repository that no longer matches the snapshot (default branch, visibility, protection state, archived, fork,
# organization-owned) is REFUSED and skipped. The first read-back mismatch or failed write stops the whole run
# (exit 4 or the failing exit code). Exit 1 means every change ran and some repositories were refused.
set -euo pipefail

APPLY_BASELINE=${APPLY_BASELINE:-__APPLY_SCRIPT__}
OWNER="__OWNER__"
BACKUP_DIR=${SAFO_BACKUP_DIR:-__BACKUP_DIR__}

ACTIONS=(
__ACTIONS__
)
SKIPPED=(
__SKIPPED__
)

apply=false
case ${1-} in
    "") ;;
    apply) apply=true ;;
    *)
        echo "usage: bash $0 [apply]" >&2
        exit 2
        ;;
esac
[ -f "$APPLY_BASELINE" ] || {
    echo "error: $APPLY_BASELINE not found" >&2
    exit 2
}

if $apply; then
    echo "APPLY: ${#ACTIONS[@]} changes. Backups go to $BACKUP_DIR (mode 0600)."
else
    echo "dry run: ${#ACTIONS[@]} changes planned, nothing is written. Run 'bash $0 apply' to write."
fi
for entry in "${SKIPPED[@]}"; do
    echo "SKIP ${entry%%|*}: ${entry#*|}"
done

refused=()
for row in "${ACTIONS[@]}"; do
    IFS='|' read -r name vis branch mode expect <<<"$row"
    args=(--repo "$OWNER/$name" --mode "$mode" --expect-branch "$branch" --expect-visibility "$vis"
        --backup-dir "$BACKUP_DIR")
    if [ "$expect" != "-" ]; then args+=(--expect-protection "$expect"); fi
    if $apply; then args+=(--apply); fi
    echo "== $OWNER/$name: $mode"
    code=0
    bash "$APPLY_BASELINE" "${args[@]}" || code=$?
    case $code in
        0) ;;
        3) refused+=("$name") ;;
        *)
            echo "STOP at $OWNER/$name ($mode): exit $code. Nothing after it was run; ROLLBACK lines above." >&2
            exit "$code"
            ;;
    esac
done

if [ ${#refused[@]} -gt 0 ]; then
    echo "refused: ${refused[*]}" >&2
    echo "refused: ${refused[*]}"
    exit 1
fi
if $apply; then
    echo "done: every change applied and read back. ROLLBACK lines are above; backups are in $BACKUP_DIR"
else
    echo "dry run finished: nothing was written"
fi
"""


def quote_dir(path: str) -> str:
    """Quote a path for bash; a leading $HOME stays a variable so the file is not tied to one account's path."""
    if path.startswith("$HOME/") and re.fullmatch(r"\$HOME/[A-Za-z0-9._/-]+", path):
        return f'"{path}"'
    return shlex.quote(path)


def render(
    actions: list[str],
    skipped: list[tuple[str, str]],
    *,
    snapshot: str,
    apply_script: str,
    owner: str,
    backup_dir: str,
) -> str:
    out = TEMPLATE
    for key, value in (
        ("__SNAPSHOT__", snapshot),
        ("__APPLY_SCRIPT__", shlex.quote(apply_script)),
        ("__OWNER__", owner),
        ("__BACKUP_DIR__", quote_dir(backup_dir)),
        ("__ACTIONS__", "\n".join(f"    {shlex.quote(a)}" for a in actions)),
        ("__SKIPPED__", "\n".join(f"    {shlex.quote(f'{n}|{why}')}" for n, why in skipped)),
    ):
        out = out.replace(key, value)
    return out


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0] if __doc__ else "")
    ap.add_argument("--audit", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--apply-script", required=True, type=Path)
    ap.add_argument("--owner", default="ChiefGyk3D")
    ap.add_argument("--backup-dir", default="$HOME/.local/share/safo-dev/backups-541")
    ap.add_argument("--skip", action="append", default=[], metavar="NAME=REASON")
    ap.add_argument("--secret", action="append", default=[], metavar="NAME")
    ns = ap.parse_args(argv)
    try:
        skips = {}
        for item in ns.skip:
            name, sep, why = item.partition("=")
            if not sep or not why.strip():
                raise ValueError(f"--skip needs NAME=REASON, got {item!r}")
            skips[name] = why.strip()
        rows = parse_audit(ns.audit.read_text(encoding="utf-8"))
        actions, skipped = plan(rows, skips, ns.secret)
    except (OSError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    if not NAME_RE.fullmatch(ns.owner):
        print("error: bad --owner", file=sys.stderr)
        return 2
    backup = ns.backup_dir
    text = render(
        actions,
        skipped,
        snapshot=ns.audit.name,
        apply_script=str(ns.apply_script.resolve()),
        owner=ns.owner,
        backup_dir=backup,
    )
    fd = os.open(ns.out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o700)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write(text)
    os.chmod(ns.out, 0o700)
    counts: dict[str, int] = {}
    for a in actions:
        mode = a.split("|")[3]
        counts[mode] = counts.get(mode, 0) + 1
    print(f"wrote {ns.out}: {len(actions)} changes {counts}, {len(skipped)} skipped")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
