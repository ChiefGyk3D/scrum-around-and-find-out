def test_legacy_choice_errors_keep_their_bytes(caller: str, vid: str) -> None:
    d = base()
    poison(d, caller, VALUES[vid])
    with pytest.raises(ConfigError) as err:
        parse_board(d)
    digest, length = PINS[(caller, vid)]
    assert (hashlib.sha256(str(err.value).encode()).hexdigest(), len(str(err.value))) == (digest, length)


