def no_raw_control(text: str) -> bool:
    return text.isascii() and text.isprintable()


def test_the_codex_repro_carries_no_escape_byte(tmp_path: Path) -> None:
    path = tmp_path / "board.yaml"
    path.write_text(CODEX_REPRO, encoding="utf-8")
    with pytest.raises(ConfigError) as err:
        load_board(path)
    message = str(err.value).replace(str(path), "board.yaml")
    assert "\x1b" not in message and no_raw_control(message) and len(message) < 300
    assert "process.phase_field: option 0 of 'Phase' must be plain text" in message


def phase_options(names: list[str]) -> dict[str, Any]:
    d = waterfall()
    for f in d["fields"]:
        if f["name"] == "Phase":
            f["options"] = [{"name": n} for n in names]
    d["process"]["gates"] = []
    return d


