def poison(d: dict[str, Any], caller: str, value: Any) -> None:
    if caller == "owner_type":
        d["project"]["owner_type"] = value
    elif caller == "field_type":
        d["fields"][0]["type"] = value
    elif caller == "color":
        d["fields"][0]["options"][0]["color"] = value
    else:
        d["views"][0]["layout"] = value


