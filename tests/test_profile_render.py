GOLDEN = Path(__file__).parent / "golden" / "harness"
HEADER = re.compile(
    r"^.*GENERATED by scripts/gen_profiles\.py from agents\.yaml; do not edit; "
    r"manifest sha256:[0-9a-f]{64}; body sha256:[0-9a-f]{64}.*$",
    re.M,
)


def masked(data: bytes) -> str:
    return HEADER.sub("HEADER", data.decode("utf-8"))


def test_the_four_harnesses_produce_exactly_these_files(tmp_path: Path) -> None:
    assert tuple(sorted(render_harness(verified(tmp_path)))) == tuple(sorted(RENDER_PATHS))


def test_the_output_matches_the_golden_files_with_the_digests_masked(tmp_path: Path) -> None:
    files = render_harness(verified(tmp_path))
    if os.environ.get("UPDATE_GOLDEN") == "1":
        for rel, r in files.items():
            (GOLDEN / rel).parent.mkdir(parents=True, exist_ok=True)
            (GOLDEN / rel).write_text(masked(r.data), encoding="utf-8")
    for rel, r in files.items():
        golden = GOLDEN / rel
        assert golden.is_file(), f"{rel}: run UPDATE_GOLDEN=1 pytest tests/test_profile_render.py"
        assert masked(r.data) == golden.read_text(encoding="utf-8"), (
            f"{rel}: UPDATE_GOLDEN=1 regenerates the golden files"
        )
    present = {str(p.relative_to(GOLDEN)) for p in GOLDEN.rglob("*") if p.is_file()}
    assert present == set(files), "a golden file without a render, or the reverse"


def test_every_file_has_one_header_with_both_digests_that_recompute(tmp_path: Path) -> None:
    v = verified(tmp_path)
    for rel, r in render_harness(v).items():
        text = r.data.decode()
        assert text.count(GENERATED_MARKER) == 1, rel
        body, manifest, body_digest = split_header(rel, r.data)
        assert body_digest == hashlib.sha256(body).hexdigest() == r.body, rel
        agent = v.agents.agent(r.agent_id)
        assert manifest == r.manifest == manifest_digest(rel, r.harness, agent, v.resolutions), rel
        assert GENERATED_MARKER.encode() not in body


def test_the_header_sits_where_its_format_puts_it(tmp_path: Path) -> None:
    files = render_harness(verified(tmp_path))
    for rel in ("claude/claude-haiku.md", "claude/claude-sonnet.md"):
        lines = files[rel].data.decode().split("\n")
        assert lines[0] == "---"
        close = lines.index("---", 1)
        assert lines[close + 1].startswith("<!-- GENERATED ") and lines[close + 1].endswith(" -->")
    for rel in ("codex/codex.prompt.md", "copilot/copilot-instructions.md"):
        assert files[rel].data.decode().split("\n")[0].startswith("<!-- GENERATED ")
    for rel in ("copilot/ISSUE_TEMPLATE/copilot-task.yml", "local/ollama.wrapper.txt"):
        assert files[rel].data.decode().split("\n")[0].startswith("# GENERATED ")


def test_the_policy_boundary_is_in_every_file_exactly_and_just_before_the_profile_section(tmp_path: Path) -> None:
    for rel, r in render_harness(verified(tmp_path)).items():
        text = r.data.decode()
        if rel.endswith(".yml"):
            form = yaml.safe_load(text)
            first = form["body"][0]
            assert first["type"] == "markdown" and BOUNDARY_PARAGRAPH in first["attributes"]["value"]
            continue
        assert text.count(BOUNDARY_PARAGRAPH) == 1, rel
        lines = text.split("\n")
        at = lines.index("## Model profile")
        previous = [x for x in lines[:at] if x.strip()][-1]
        assert previous == BOUNDARY_PARAGRAPH, rel


def test_the_issue_form_parses_and_has_every_required_field(tmp_path: Path) -> None:
    text = render_harness(verified(tmp_path))["copilot/ISSUE_TEMPLATE/copilot-task.yml"].data.decode()
    assert text.startswith("# GENERATED ")
    form = yaml.safe_load(text)
    assert set(form) >= {"name", "description", "body"}
    body = form["body"]
    assert body[0]["type"] == "markdown"
    assert "reviewed by a different agent" in body[0]["attributes"]["value"]
    assert "Keep the pull request small" in body[1]["attributes"]["value"]  # brief.inline is one extra block
    fields = {b["id"]: b for b in body if "id" in b}
    assert set(fields) == {"acceptance_criteria", "files_in_scope", "test_command", "no_new_dependencies"}
    for b in fields.values():
        assert (
            b["validations"]["required"] is True
            if b["type"] != "checkboxes"
            else b["attributes"]["options"][0]["required"]
        )
    assert fields["acceptance_criteria"]["type"] == "textarea" and fields["files_in_scope"]["type"] == "textarea"
    assert fields["test_command"]["type"] == "input"
    assert fields["no_new_dependencies"]["type"] == "checkboxes"


def test_a_claude_file_starts_with_its_front_matter_and_copies_tools_only_from_the_persona(tmp_path: Path) -> None:
    files = render_harness(verified(tmp_path))
    data = files["claude/claude-sonnet.md"].data
    assert data.startswith(b"---\n")
    front = yaml.safe_load(data.decode().split("---\n")[1])
    assert front["name"] == "claude-sonnet" and front["tools"] == "Read, Grep, Glob"
    assert front["disallowedTools"] == ["Write", "Edit"]
    assert set(front) == {"name", "description", "model", "tools", "disallowedTools"} and front["model"] == "sonnet"
    haiku = yaml.safe_load(files["claude/claude-haiku.md"].data.decode().split("---\n")[1])
    assert haiku["model"] == "haiku" and "tools" not in haiku and "disallowedTools" not in haiku
    assert "Find what is wrong. Do not fix it." in data.decode()  # the persona body, without its own front matter
    assert data.decode().count("---\n") == 2


def test_the_profile_section_is_a_fixed_structure_with_a_pointer_on_every_list_line(tmp_path: Path) -> None:
    files = render_harness(verified(tmp_path))
    for rel, r in files.items():
        if rel.endswith(".yml"):
            continue
        text = r.data.decode()
        assert text.count("\n## Model profile\n") == 1, rel
        section = text.split("\n## Model profile\n", 1)[1]
        for line in section.split("\n"):
            if line.startswith("- ") and line.endswith(")") and "(`" in line:
                assert re.search(r" \(`(lessons|outcomes|config):[^`\s]+`\)$", line), (rel, line)
    codex = files["codex/codex.prompt.md"].data.decode()
    assert (
        "- Expect it to commit inside a git worktree. (`lessons:codexs-sandbox-cannot-commit-inside-a-git-worktree`)"
        in codex
    )
    assert "### Do not\n" in codex and "### Do\n" in codex
    assert "{{task}}" in codex and "{{files_in_scope}}" in codex  # the template is rendered as written
    haiku = files["claude/claude-haiku.md"].data.decode()
    assert "### Must not be given\n\n- security-sensitive-code (`lessons:" in haiku


