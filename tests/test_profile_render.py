GOLDEN = Path(__file__).parent / "golden" / "harness"
HEADER = re.compile(
    r"^.*GENERATED by scripts/gen_profiles\.py from agents\.yaml; do not edit; "
    r"manifest sha256:[0-9a-f]{64}; body sha256:[0-9a-f]{64}.*$",
    re.M,
)


def masked(data: bytes) -> str:
    return HEADER.sub("HEADER", data.decode("utf-8"))


def test_the_four_harnesses_produce_exactly_these_files(tmp_path: Path) -> None:
    assert tuple(sorted(render_harness(verified(tmp_path)))) == tuple(sorted(RENDER_PATHS))


def test_the_output_matches_the_golden_files_with_the_digests_masked(tmp_path: Path) -> None:
    files = render_harness(verified(tmp_path))
    if os.environ.get("UPDATE_GOLDEN") == "1":
        for rel, r in files.items():
            (GOLDEN / rel).parent.mkdir(parents=True, exist_ok=True)
            (GOLDEN / rel).write_text(masked(r.data), encoding="utf-8")
    for rel, r in files.items():
        golden = GOLDEN / rel
        assert golden.is_file(), f"{rel}: run UPDATE_GOLDEN=1 pytest tests/test_profile_render.py"
        assert masked(r.data) == golden.read_text(encoding="utf-8"), (
            f"{rel}: UPDATE_GOLDEN=1 regenerates the golden files"
        )
    present = {str(p.relative_to(GOLDEN)) for p in GOLDEN.rglob("*") if p.is_file()}
    assert present == set(files), "a golden file without a render, or the reverse"


def test_every_file_has_one_header_with_both_digests_that_recompute(tmp_path: Path) -> None:
    v = verified(tmp_path)
    for rel, r in render_harness(v).items():
        text = r.data.decode()
        assert text.count(GENERATED_MARKER) == 1, rel
        body, manifest, body_digest = split_header(rel, r.data)
        assert body_digest == hashlib.sha256(body).hexdigest() == r.body, rel
        agent = v.agents.agent(r.agent_id)
        assert manifest == r.manifest == manifest_digest(rel, r.harness, agent, v.resolutions), rel
        assert GENERATED_MARKER.encode() not in body


