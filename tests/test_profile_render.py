def test_the_rendering_does_not_depend_on_the_working_directory(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    a = render_harness(verified(tmp_path / "a"))
    monkeypatch.chdir(tmp_path)
    b = render_harness(verified(tmp_path / "b"))
    assert {k: v.data for k, v in a.items()} == {k: v.data for k, v in b.items()}


