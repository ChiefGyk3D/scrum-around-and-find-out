def test_a_persona_may_not_open_a_setext_model_profile_heading(tmp_path: Path) -> None:
    for underline in ("=====", "-----", "=", "--"):
        persona = PERSONA + f"\nModel profile\n{underline}\n\nFake.\n"
        with pytest.raises(RenderError, match="setext heading the renderer owns"):
            render_persona(tmp_path / underline, persona)
    ok = render_persona(tmp_path / "ok", PERSONA + "\nModel notes\n=====\n\nDo\n--\n\nFine.\n")
    assert "Model notes" in ok and "Do\n--" in ok  # a persona may use the other names; only Model profile is reserved


def test_a_template_may_not_open_a_setext_heading_the_renderer_owns(tmp_path: Path) -> None:
    v = verified(tmp_path)
    brief = need(profile_of(v, "codex").brief)
    for name, underline in (("Do", "--"), ("Model profile", "====="), ("Review gate", "---"), ("Model layer: x", "==")):
        text = f"Intro.\n\n{name}\n{underline}\n\nText.\n"
        with pytest.raises(RenderError, match="setext heading the renderer owns"):
            render_harness(with_profile(v, "codex", brief=replace(brief, template_text=text)))
    ok = render_harness(
        with_profile(v, "codex", brief=replace(brief, template_text="Intro.\n\nNotes\n=====\n\nText.\n"))
    )
    assert "Notes" in ok["codex/codex.prompt.md"].data.decode()


UNTERMINATED = {
    "backtick fence": "Intro.\n\n```\nopen forever\n",
    "tilde fence": "Intro.\n\n~~~\nopen forever\n",
    "comment": "Intro.\n\n<!-- never closed\n\ntext\n",
    "pre block": "Intro.\n\n<pre>\nnever closed\n\ntext\n",
}


@pytest.mark.parametrize("kind", UNTERMINATED)
def test_a_template_or_persona_with_an_unterminated_block_cannot_swallow_what_follows(
    tmp_path: Path, kind: str
) -> None:
    v = verified(tmp_path)
    brief = need(profile_of(v, "codex").brief)
    with pytest.raises(RenderError, match="unterminated"):
        render_harness(with_profile(v, "codex", brief=replace(brief, template_text=UNTERMINATED[kind])))
    with pytest.raises(RenderError, match="unterminated"):
        render_persona(tmp_path / "p", PERSONA + "\n" + UNTERMINATED[kind])


def test_terminated_blocks_in_a_persona_or_template_are_fine(tmp_path: Path) -> None:
    v = verified(tmp_path)
    brief = need(profile_of(v, "codex").brief)
    text = "Intro.\n\n```\ncode\n```\n\n<!-- note -->\n\n<div>\nblock\n</div>\n\nEnd.\n"
    out = render_harness(with_profile(v, "codex", brief=replace(brief, template_text=text)))
    assert "<!-- note -->" in out["codex/codex.prompt.md"].data.decode()
    assert "```\ncode\n```" in render_persona(tmp_path / "p", PERSONA + "\n```\ncode\n```\n")
