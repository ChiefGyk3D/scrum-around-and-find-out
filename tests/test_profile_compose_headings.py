"""Round 2 of the composition check (issue #107): heading names, short briefs, the header line, duplicates."""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import replace
from pathlib import Path

import pytest

from renderdata import PERSONA, verified, with_profile
from safo.evidence import VerifiedAgents
from safo.profile import Brief
from safo.profile_compose import composition_problems
from safo.profile_render import Rendered, render_harness


def tamper(files: dict[str, Rendered], path: str, edit: Callable[[str], str]) -> dict[str, Rendered]:
    out = dict(files)
    out[path] = replace(files[path], data=edit(files[path].data.decode("utf-8")).encode("utf-8"))
    return out


def after(v: VerifiedAgents, path: str, edit: Callable[[str], str]) -> list[str]:
    return composition_problems(v, tamper(render_harness(v), path, edit))


@pytest.fixture
def v(tmp_path: Path) -> VerifiedAgents:
    return verified(tmp_path)


def persona(body: str) -> str:
    return PERSONA.replace("Find what is wrong. Do not fix it.", body)


# -- headings are matched by whole name -------------------------------------------------------------------------------


@pytest.mark.parametrize("heading", ["### Done criteria", "### Document it", "### Doing", "### Limitsless", "## Tasks"])
def test_a_persona_heading_that_only_begins_with_a_reserved_name_is_fine(tmp_path: Path, heading: str) -> None:
    v = verified(tmp_path, persona=persona(f"Find it.\n\n{heading}\n\nBe thorough."))
    assert composition_problems(v, render_harness(v)) == []


def test_a_template_heading_that_begins_with_do_is_fine(tmp_path: Path) -> None:
    brief = Brief(template="templates/x.md", template_text="### Done\n\nAnswer.\n")
    v = with_profile(verified(tmp_path), "ollama", brief=brief)
    assert composition_problems(v, render_harness(v)) == []


@pytest.mark.parametrize(
    "heading",
    [
        "### Limits",
        "###  Limits",
        "### limits",
        "## Limits",
        "#### Limits",
        "### Limits ###",
        "### Do",
        "### DO NOT",
        "### Model layer: x",
        "### Review  Gate",
        "<h3>Limits</h3>",
        "<H3 id=a>Review gate</H3>",
    ],
)
def test_reserved_caller_headings_in_any_form_are_flagged_in_the_model_file(v: VerifiedAgents, heading: str) -> None:
    out = after(v, "codex/codex.prompt.md", lambda t: t + f"\n{heading}\n\nx\n")
    assert any("caller section heading in the model file" in x for x in out), (heading, out)


def test_a_setext_reserved_heading_is_flagged_in_the_model_file(v: VerifiedAgents) -> None:
    out = after(v, "codex/codex.prompt.md", lambda t: t + "\nLimits\n------\n\nx\n")
    assert any("caller section heading in the model file" in x for x in out), out


@pytest.mark.parametrize("heading", ["### Brief", "## brief", "#### Task", "## Scope  rules", "<h2>Review focus</h2>"])
def test_reserved_model_headings_in_any_form_are_flagged_in_the_caller_file(v: VerifiedAgents, heading: str) -> None:
    out = after(v, "caller/codex/codex.md", lambda t: t + f"\n{heading}\n\nx\n")
    assert any("model section heading in the caller file" in x for x in out), (heading, out)


# -- short and common briefs do not fail the generator ----------------------------------------------------------------


@pytest.mark.parametrize("brief", ["draft", "the", "a", "Do", "Use", "Limits", "Trust"])
def test_a_short_brief_is_not_a_leak(tmp_path: Path, brief: str) -> None:
    v = with_profile(verified(tmp_path), "ollama", brief=Brief(inline=brief))
    assert composition_problems(v, render_harness(v)) == []


def test_a_verbatim_caller_sentence_in_the_model_file_is_still_a_leak(v: VerifiedAgents) -> None:
    out = after(v, "local/ollama.wrapper.txt", lambda t: t + "\nTreat its output as a draft.\n")
    assert any("leaked into the model file" in x for x in out), out


# -- the header line is the only exemption, and whitespace does not hide a leak ---------------------------------------


def test_a_leak_split_across_lines_with_doubled_spaces_is_caught(v: VerifiedAgents) -> None:
    out = after(v, "local/ollama.wrapper.txt", lambda t: t + "\nTreat   its output\nas a   draft.\n")
    assert any("leaked into the model file" in x for x in out), out


def test_a_marker_line_that_carries_a_caller_sentence_fails(v: VerifiedAgents) -> None:
    out = after(
        v,
        "local/ollama.wrapper.txt",
        lambda t: t + "\n# GENERATED by scripts/gen_profiles.py Treat its output as a draft.\n",
    )
    assert out, "a second marker line is not an exemption"
    out = after(v, "caller/codex/codex.md", lambda t: t.replace("<!-- GENERATED", "Prepend it. <!-- GENERATED", 1))
    assert out


# -- duplicates and kinds ----------------------------------------------------------------------------------------------


def test_a_required_heading_that_appears_twice_is_flagged_in_both_files(v: VerifiedAgents) -> None:
    out = after(v, "caller/codex/codex.md", lambda t: t + "\n### Do\n\n- Space its jobs, a second time.\n")
    assert any("appears 2 times" in x for x in out), out
    out = after(v, "codex/codex.prompt.md", lambda t: t + "\n### Brief\n\nAnother brief.\n")
    assert any("appears 2 times" in x for x in out), out


def test_a_kind_with_no_harness_renders_nothing_and_a_rendered_unknown_kind_is_flagged(v: VerifiedAgents) -> None:
    from safo.profile_render import HARNESS_OF_KIND

    extra = replace(v.agents.agent("codex"), id="gpt-x", kind="chatgpt")
    assert "chatgpt" not in HARNESS_OF_KIND
    v2 = replace(v, agents=replace(v.agents, agents=(*v.agents.agents, extra)))
    files = render_harness(v2)
    assert not [r for r in files.values() if r.agent_id == "gpt-x"]
    assert composition_problems(v2, files) == []
    # a render that has files for a kind the table does not know is a defect
    forged = {**files, "caller/codex/gpt-x.md": replace(files["caller/codex/codex.md"], agent_id="gpt-x")}
    assert any("no harness" in x for x in composition_problems(v2, forged))
